// lib/data/models/attendance_record.dart
class AttendanceRecord {
  final int studentId;
  final String studentName;
  final String studentLastName;
  final String? beltColor;
  bool isPresent; // ✅ جعلها غير final
  bool wasAutoGenerated; // ✅ جعلها غير final
  DateTime? markedAt; // ✅ جعلها غير final
  String? excuseReason; // ✅ جعلها غير final

  AttendanceRecord({
    required this.studentId,
    required this.studentName,
    required this.studentLastName,
    this.beltColor,
    required this.isPresent,
    required this.wasAutoGenerated,
    this.markedAt,
    this.excuseReason,
  });

  Map<String, dynamic> toMap() {
    return {
      'student_id': studentId,
      'student_name': studentName,
      'student_last_name': studentLastName,
      'belt_color': beltColor,
      'is_present': isPresent ? 1 : 0,
      'was_auto_generated': wasAutoGenerated ? 1 : 0,
      'marked_at': markedAt?.toIso8601String(),
      'excuse_reason': excuseReason,
    };
  }

  factory AttendanceRecord.fromMap(Map<String, dynamic> map) {
    return AttendanceRecord(
      studentId: map['student_id'],
      studentName: map['student_name'],
      studentLastName: map['student_last_name'],
      beltColor: map['belt_color'],
      isPresent: map['is_present'] == 1,
      wasAutoGenerated: map['was_auto_generated'] == 1,
      markedAt: map['marked_at'] != null
          ? DateTime.parse(map['marked_at'])
          : null,
      excuseReason: map['excuse_reason'],
    );
  }
}
