import 'package:sqflite/sqflite.dart';
import 'package:connectivity_plus/connectivity_plus.dart';
import '../models/attendance_record.dart';
import '../../domain/repositories/i_attendance_repository.dart';
import '../datasources/local/app_database.dart';
import '../datasources/remote/supabase_client.dart';

class AttendanceRepository implements IAttendanceRepository {
  final AppDatabase _localDb;
  final SupabaseClient _remoteApi;
  final Connectivity _connectivity;

  AttendanceRepository({
    required AppDatabase localDb,
    required SupabaseClient remoteApi,
    required Connectivity connectivity,
  })  : _localDb = localDb,
        _remoteApi = remoteApi,
        _connectivity = connectivity;

  Future<Database> get _db async => await _localDb.database;

  @override
  Future<bool> checkConnectivity() async {
    final result = await _connectivity.checkConnectivity();
    return result != ConnectivityResult.none;
  }

  @override
  Future<bool> hasPendingOperations() async {
    final db = await _db;
    final result = await db.query(
      'pending_operations',
      where: 'synced = 0 AND table_name = "attendances"',
    );
    return result.isNotEmpty;
  }

  /// جلب الحضور لحصة محددة
  Future<List<AttendanceRecord>> getAttendanceForSession({
    required int sessionId,
    required int groupId,
  }) async {
    final db = await _db;
    print('🔍 getAttendanceForSession: sessionId=$sessionId, groupId=$groupId');

    // جلب طلاب الفوج مباشرة
    final students = await db.query(
      'students',
      where: 'group_id = ? AND is_active = 1',
      whereArgs: [groupId],
    );

    print('🔍 getAttendanceForSession: تم جلب ${students.length} طالب');

    List<AttendanceRecord> records = [];

    for (var student in students) {
      final studentId = student['id'] as int;
      final firstName = student['first_name'] as String? ?? '';
      final lastName = student['last_name'] as String? ?? '';

      // البحث عن سجل الحضور لهذه الحصة
      final attendanceResult = await db.query(
        'attendances',
        where: 'student_id = ? AND session_id = ?',
        whereArgs: [studentId, sessionId],
      );

      if (attendanceResult.isNotEmpty) {
        final att = attendanceResult.first;
        DateTime? sessionDate;
        if (att['session_date'] != null) {
          try {
            sessionDate = DateTime.parse(att['session_date'] as String);
          } catch (e) {
            sessionDate = null;
          }
        }

        DateTime? markedAt;
        final markedAtValue = att['marked_at'];
        if (markedAtValue != null && markedAtValue is String) {
          try {
            markedAt = DateTime.parse(markedAtValue);
          } catch (e) {
            markedAt = null;
          }
        }

        records.add(AttendanceRecord(
          studentId: studentId,
          sessionId: sessionId,
          studentName: firstName,
          studentLastName: lastName,
          sessionDate: sessionDate ?? DateTime.now(),
          isPresent: att['is_present'] == 1,
          wasAutoGenerated: att['was_auto_generated'] == 1,
          markedAt: markedAt,
          excuseReason: att['excuse_reason'] as String?,
        ));
      } else {
        // إنشاء سجل غياب تلقائي
        await db.insert('attendances', {
          'student_id': studentId,
          'session_id': sessionId,
          'session_date': DateTime.now().toIso8601String().split('T').first,
          'is_present': 0,
          'was_auto_generated': 1,
        });

        records.add(AttendanceRecord(
          studentId: studentId,
          sessionId: sessionId,
          studentName: firstName,
          studentLastName: lastName,
          sessionDate: DateTime.now(),
          isPresent: false,
          wasAutoGenerated: true,
        ));
      }
    }

    print('🔍 getAttendanceForSession: تم إنشاء ${records.length} سجل');
    return records;
  }

  @override
  Future<List<AttendanceRecord>> getAttendanceForGroup({
    required int groupId,
    required DateTime date,
  }) async {
    final db = await _db;
    final dateStr = date.toIso8601String().split('T').first;

    // جلب جميع حصص هذا الفوج في هذا اليوم
    final sessions = await db.query(
      'sessions',
      where: 'group_id = ? AND day_of_week = ?',
      whereArgs: [groupId, date.weekday == 7 ? 0 : date.weekday],
    );

    print('🔍 getAttendanceForGroup: تم جلب ${sessions.length} حصة');

    List<AttendanceRecord> allRecords = [];

    for (var session in sessions) {
      final sessionId = session['id'] as int;
      // ✅ تمرير groupId مع sessionId
      final records = await getAttendanceForSession(
        sessionId: sessionId,
        groupId: groupId,
      );
      allRecords.addAll(records);
    }

    return allRecords;
  }

  @override
  Future<void> markPresent({
    required int studentId,
    required int groupId,
    required DateTime date,
    bool viaQR = false,
  }) async {
    final db = await _db;
    final dateStr = date.toIso8601String().split('T').first;

    await db.update(
      'attendances',
      {
        'is_present': 1,
        'was_auto_generated': 0,
        'marked_at': DateTime.now().toIso8601String(),
      },
      where: 'student_id = ? AND session_date = ?',
      whereArgs: [studentId, dateStr],
    );
  }

  @override
  Future<void> markAbsent({
    required int studentId,
    required int groupId,
    required DateTime date,
    String? excuseReason,
  }) async {
    final db = await _db;
    final dateStr = date.toIso8601String().split('T').first;

    await db.update(
      'attendances',
      {'is_present': 0, 'was_auto_generated': 0, 'excuse_reason': excuseReason},
      where: 'student_id = ? AND session_date = ?',
      whereArgs: [studentId, dateStr],
    );
  }

  @override
  Future<bool> isStudentInGroup({
    required int studentId,
    required int groupId,
  }) async {
    final db = await _db;
    final result = await db.query(
      'students',
      where: 'id = ? AND group_id = ? AND is_active = 1',
      whereArgs: [studentId, groupId],
    );
    return result.isNotEmpty;
  }

  @override
  Future<String?> decodeQR(String qrData) async {
    try {
      final studentId = int.parse(qrData);
      final db = await _db;
      final result = await db.query(
        'students',
        where: 'id = ? AND is_active = 1',
        whereArgs: [studentId],
      );
      if (result.isNotEmpty) {
        return studentId.toString();
      }
      return null;
    } catch (e) {
      return null;
    }
  }

  @override
  Future<List<AttendanceRecord>> getStudentAttendance({
    required int studentId,
    int limit = 5,
  }) async {
    final db = await _db;
    print('🔍 getStudentAttendance: جلب سجلات الطالب $studentId');

    final result = await db.query(
      'attendances',
      where: 'student_id = ?',
      whereArgs: [studentId],
      orderBy: 'session_date DESC',
      limit: limit,
    );

    print('🔍 getStudentAttendance: تم جلب ${result.length} سجل');

    // جلب اسم الطالب
    final studentResult = await db.query(
      'students',
      where: 'id = ?',
      whereArgs: [studentId],
    );
    final studentName = studentResult.isNotEmpty
        ? (studentResult.first['first_name'] as String? ?? '')
        : '';
    final studentLastName = studentResult.isNotEmpty
        ? (studentResult.first['last_name'] as String? ?? '')
        : '';

    List<AttendanceRecord> records = [];

    for (var map in result) {
      try {
        final sessionId = map['session_id'] as int? ?? 0;

        DateTime? sessionDate;
        if (map['session_date'] != null) {
          try {
            final dateStr = map['session_date'] as String;
            sessionDate = DateTime.parse(dateStr);
          } catch (e) {
            sessionDate = null;
          }
        }

        DateTime? markedAt;
        final markedAtValue = map['marked_at'];
        if (markedAtValue != null && markedAtValue is String) {
          try {
            markedAt = DateTime.parse(markedAtValue);
          } catch (e) {
            markedAt = null;
          }
        }

        records.add(AttendanceRecord(
          studentId: studentId,
          sessionId: sessionId,
          studentName: studentName,
          studentLastName: studentLastName,
          sessionDate: sessionDate ?? DateTime.now(),
          isPresent: map['is_present'] == 1,
          wasAutoGenerated: map['was_auto_generated'] == 1,
          markedAt: markedAt,
          excuseReason: map['excuse_reason'] as String?,
        ));
      } catch (e) {
        print('❌ خطأ في معالجة سجل: $e');
        print('   السجل: $map');
      }
    }

    print('🔍 getStudentAttendance: تم إنشاء ${records.length} سجل');
    return records;
  }

  /// جلب سجل الحضور لفوج معين خلال فترة زمنية
  @override
  Future<List<AttendanceRecord>> getAttendanceForGroupByDateRange({
    required int groupId,
    required DateTime startDate,
    required DateTime endDate,
  }) async {
    final db = await _db;
    final startDateStr = startDate.toIso8601String().split('T').first;
    final endDateStr = endDate.toIso8601String().split('T').first;

    // جلب جميع الحصص في هذه الفترة
    final sessions = await db.query(
      'sessions',
      where: 'group_id = ?',
      whereArgs: [groupId],
    );

    print('🔍 getAttendanceForGroupByDateRange: تم جلب ${sessions.length} حصة');

    List<AttendanceRecord> allRecords = [];

    for (var session in sessions) {
      final sessionId = session['id'] as int;
      // ✅ تمرير groupId مع sessionId
      final records = await getAttendanceForSession(
        sessionId: sessionId,
        groupId: groupId,
      );

      // تصفية حسب التاريخ
      final filtered = records
          .where((r) =>
              r.sessionDate != null &&
              r.sessionDate!.isAfter(startDate) &&
              r.sessionDate!.isBefore(endDate))
          .toList();
      allRecords.addAll(filtered);
    }

    print(
        '🔍 getAttendanceForGroupByDateRange: تم إنشاء ${allRecords.length} سجل');
    return allRecords;
  }
}
